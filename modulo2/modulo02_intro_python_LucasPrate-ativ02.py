# Impressão da mensagem inicial
saudacao = "Olá, Mundo!"
print(saudacao)

# Armazenando valores de diferentes tipos primitivos em variáveis
texto = "Olá, Mundo!"
inteiro = 10
decimal = 3.14
booleano = True

# Exibindo os tipos de cada dado com f-strings
print(f"Tipo de '{texto}': {type(texto)}")
print(f"Tipo de {inteiro}: {type(inteiro)}")
print(f"Tipo de {decimal}: {type(decimal)}")
print(f"Tipo de {booleano}: {type(booleano)}")